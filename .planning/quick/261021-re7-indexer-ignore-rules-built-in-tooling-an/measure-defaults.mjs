const median = (xs) => [...xs].sort((a, b) => a - b)[Math.floor(xs.length / 2)];

async function timed(fn) {
  const runs = [];
  for (let i = 0; i < 3; i += 1) runs.push(await fn());
  return median(runs);
}

function scratchRepoFromPin() {
  const root = path.join(scratchDir(), 're7-cost-gsdcore');
  if (fs.existsSync(path.join(root, '.git'))) return root;
  fs.rmSync(root, { recursive: true, force: true });
  fs.mkdirSync(root, { recursive: true });
  const archive = path.join(scratchDir(), 're7-core-pin.tar');
  const a = spawnSync('git', ['archive', '--format=tar', '-o', archive, CORPORA[0].pin], { cwd: coreDir(), env: gitEnv(), encoding: 'buffer' });
  if (a.status !== 0) throw new Error(`git archive failed: ${a.stderr.toString()}`);
  const t = spawnSync('tar', ['-xf', archive, '-C', root]);
  if (t.status !== 0) throw new Error('tar failed');
  git(['init', '-q'], root);
  git(['add', '-A'], root);
  git(['-c', 'user.name=m', '-c', 'user.email=m@example.invalid', 'commit', '-q', '-m', 'pin'], root);
  return root;
}

function scratchCopyOfTypeScript() {
  const root = path.join(scratchDir(), 're7-cost-typescript');
  if (fs.existsSync(path.join(root, '.git'))) return root;
  fs.rmSync(root, { recursive: true, force: true });
  const cp = spawnSync('cp', ['-cR', path.join(scratchDir(), 'corpora', 'TypeScript'), root]);
  if (cp.status !== 0) throw new Error('cp failed');
  return root;
}

async function cost() {
  const defaults = PROPOSED.flatMap((e) => ['--exclude', e.pattern]);
  const decided = fs.existsSync(MEASUREMENTS) ? readDecisions(fs.readFileSync(MEASUREMENTS, 'utf8')) : new Map();
  const tracked = PROPOSED.filter((e) => decided.get(e.pattern)?.decision === 'TRACKED-OK').flatMap((e) => ['--exclude', e.pattern]);
  const atl = [
    '# ten representative lines', 'docs/generated/', '*.snap', '/fixtures/big/', 'tests/**/data/', '!tests/keep/data/', '*.log', 'tmp-*', 'legacy/', '**/vendor/', 'misc/*.json',
  ].join('\n') + '\n';
  const lines = ['| repo | tracked | old single listing | new unignored stage 1 (A_std ∥ D_def) | new snapshot stage 1 (T ∥ R_std ∥ D_def ∥ U0) | old snapshot (T then others) | R_atl | argv bytes |', '| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |'];
  for (const [label, root] of [['gsd-core (pin, scratch export)', scratchRepoFromPin()], ['TypeScript (scratch copy)', scratchCopyOfTypeScript()]]) {
    fs.writeFileSync(path.join(root, '.atlasignore'), atl);
    const count = split0(git(['ls-files', '-z', '--cached'], root).stdout).length;
    const old = await timed(async () => (await gitAsync(['ls-files', '-z', '--cached', '--others', '--exclude-standard'], root)).ms);
    const unign = await timed(async () => {
      const t0 = process.hrtime.bigint();
      await Promise.all([
        gitAsync(['ls-files', '-z', '--cached', '--others', '--exclude-standard', ...defaults], root),
        gitAsync(['ls-files', '-z', '--cached', '--ignored', ...(tracked.length ? tracked : ['--exclude', 'node_modules/'])], root),
      ]);
      return Number(process.hrtime.bigint() - t0) / 1e6;
    });
    const snap = await timed(async () => {
      const t0 = process.hrtime.bigint();
      await Promise.all([
        gitAsync(['ls-files', '-z', '-s'], root),
        gitAsync(['ls-files', '-z', '--others', '--exclude-standard', ...defaults], root),
        gitAsync(['ls-files', '-z', '--cached', '--ignored', ...(tracked.length ? tracked : ['--exclude', 'node_modules/'])], root),
        gitAsync(['ls-files', '-z', '--others', '--exclude-standard'], root),
      ]);
      return Number(process.hrtime.bigint() - t0) / 1e6;
    });
    const oldSnap = await timed(async () => {
      const t0 = process.hrtime.bigint();
      await gitAsync(['ls-files', '-z', '-s'], root);
      await gitAsync(['ls-files', '-z', '--others', '--exclude-standard'], root);
      return Number(process.hrtime.bigint() - t0) / 1e6;
    });
    const ratl = await timed(async () => (await gitAsync(['ls-files', '-z', '--others', '--exclude-per-directory=.atlasignore', ...defaults], root)).ms);
    lines.push(`| ${label} | ${String(count)} | ${old.toFixed(0)} ms | ${unign.toFixed(0)} ms | ${snap.toFixed(0)} ms | ${oldSnap.toFixed(0)} ms | ${ratl.toFixed(0)} ms | ${String(argvBytes())} |`);
  }
  return lines.join('\n');
}

// ---------------------------------------------------------------- MEASUREMENTS.md parsing

function sectionOf(text, heading) {
  const start = text.indexOf(`\n${heading}\n`);
  if (start === -1) return null;
  const from = start + heading.length + 2;
  const next = text.indexOf('\n## ', from);
  return text.slice(from, next === -1 ? text.length : next);
}

function tableRows(section) {
  return section
    .split('\n')
    .filter((l) => l.startsWith('|') && !/^\|\s*-/.test(l))
    .map((l) => l.replace(/^\||\|\s*$/g, '').split('|').map((c) => c.trim()));
}

const unquote = (s) => s.replace(/^`|`$/g, '');

function readDecisions(text) {
  const section = sectionOf(text, '## Per-entry decision');
  if (section === null) return new Map();
  const map = new Map();
  for (const cells of tableRows(section)) {
    if (cells.length < 4 || !cells[0].startsWith('`')) continue;
    map.set(unquote(cells[0]), { ecosystem: cells[1], decision: cells[2], reason: cells.slice(3).join('|').trim() });
  }
  return map;
}

function readDropTotals(text) {
  const section = sectionOf(text, '## Tracked-path drops per entry');
  if (section === null) return new Map();
  const map = new Map();
  for (const cells of tableRows(section)) {
    if (!cells[0].startsWith('`')) continue;
    map.set(unquote(cells[0]), Number.parseInt(cells[cells.length - 1], 10));
  }
  return map;
}

function check() {
  const problems = [];
  const say = (m) => problems.push(m);
  if (!fs.existsSync(MEASUREMENTS)) {
    say(`missing ${path.basename(MEASUREMENTS)}`);
    return problems;
  }
  const text = fs.readFileSync(MEASUREMENTS, 'utf8');
  let at = -1;
  for (const h of HEADINGS) {
    const i = text.indexOf(`\n${h}\n`);
    if (i === -1) say(`missing heading: ${h}`);
    else if (i < at) say(`heading out of order: ${h}`);
    else at = i;
  }
  const decisions = readDecisions(text);
  const totals = readDropTotals(text);
  const proposed = new Set(PROPOSED.map((e) => e.pattern));
  for (const e of PROPOSED) {
    const d = decisions.get(e.pattern);
    const total = totals.get(e.pattern);
    if (total === undefined || Number.isNaN(total)) say(`no drops row for ${e.pattern}`);
    if (d === undefined) {
      say(`no decision row for ${e.pattern}`);
      continue;
    }
    if (d.ecosystem !== e.ecosystem) say(`${e.pattern}: ecosystem ${d.ecosystem} differs from ${e.ecosystem}`);
    if (d.decision !== 'TRACKED-OK' && d.decision !== 'UNTRACKED-ONLY') say(`${e.pattern}: decision must be TRACKED-OK or UNTRACKED-ONLY, got "${d.decision}"`);
    if (d.reason.length < 15) say(`${e.pattern}: reason is missing or too short`);
    if (!MEASURED_ECOSYSTEMS.has(e.ecosystem)) {
      if (d.decision !== 'UNTRACKED-ONLY' || !/not measured/i.test(d.reason)) say(`${e.pattern}: an unmeasured ecosystem must be UNTRACKED-ONLY with the reason "not measured"`);
    } else if (e.ecosystem === 'javascript' && total !== undefined && !Number.isNaN(total)) {
      if (total === 0 && d.decision !== 'TRACKED-OK') say(`${e.pattern}: zero source-extension drops requires TRACKED-OK`);
      if (total > NEGLIGIBLE_ALLOWANCE && d.decision !== 'UNTRACKED-ONLY') say(`${e.pattern}: ${String(total)} source-extension drops requires UNTRACKED-ONLY`);
      if (total > 0 && total <= NEGLIGIBLE_ALLOWANCE && d.decision === 'TRACKED-OK' && !/allowance/i.test(d.reason)) say(`${e.pattern}: TRACKED-OK with ${String(total)} drops needs the logged allowance in the reason`);
    }
  }
  for (const key of decisions.keys()) if (!proposed.has(key)) say(`decision row for an entry that is not proposed: ${key}`);
  const core = /before:.*`\.git\/index` sha256 ([0-9a-f]{64})[\s\S]*?after:.*`\.git\/index` sha256 ([0-9a-f]{64})/.exec(text);
  if (core === null) say('the gsd-core before/after index checksums are not recorded');
  else if (core[1] !== core[2]) say('the gsd-core clone index checksum changed');
  const stat = /before:.*\(sha ([0-9a-f]{12})\)[\s\S]*?after:.*\(sha ([0-9a-f]{12})\)/.exec(text);
  if (stat === null) say('the gsd-core before/after status is not recorded');
  else if (stat[1] !== stat[2]) say('the gsd-core clone status changed');
  const probes = sectionOf(text, '## Git behaviour probes') ?? '';
  for (let q = 1; q <= 8; q += 1) if (!new RegExp(`\\bQ${String(q)}\\b`).test(probes)) say(`probe Q${String(q)} is not recorded`);
  const notMeasured = sectionOf(text, '## Not measured') ?? '';
  if (!/Windows/.test(notMeasured)) say('Not measured must mention Windows and Linux git timing');
  return problems;
}

function emitTs() {
  const text = fs.readFileSync(MEASUREMENTS, 'utf8');
  const decisions = readDecisions(text);
  const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  const lines = ['export const INDEX_DEFAULT_EXCLUDES: readonly IndexDefaultExclude[] = ['];
  for (const e of PROPOSED) {
    const d = decisions.get(e.pattern);
    if (d === undefined) throw new Error(`no decision for ${e.pattern}`);
    lines.push(`  { pattern: ${q(e.pattern)}, ecosystem: ${q(e.ecosystem)}, appliesToTracked: ${d.decision === 'TRACKED-OK' ? 'true' : 'false'}, rationale: ${q(e.rationale)} },`);
  }
  lines.push('];');
  return lines.join('\n');
}

// ---------------------------------------------------------------- main

const arg = process.argv[2];
if (arg === '--check') {
  const problems = check();
  if (problems.length > 0) {
    for (const p of problems) process.stderr.write(`${p}\n`);
    process.exit(1);
  }
  process.stdout.write('ok\n');
} else if (arg === '--emit-ts') {
  process.stdout.write(`${emitTs()}\n`);
} else if (arg === '--snapshot-core') {
  const s = snapshotCore();
  process.stdout.write(`status-lines=${String(s.statusLines)} status-sha=${s.statusSha} index-sha256=${s.indexSha256}\n`);
} else if (arg === '--cost') {
  process.stdout.write(`${await cost()}\n`);
} else if (arg === undefined) {
  process.stdout.write(`${measure()}\n`);
} else {
  process.stderr.write(`unknown argument ${arg}\n`);
  process.exit(2);
}
