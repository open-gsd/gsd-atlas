function measure() {
  const before = snapshotCore();
  const opened = CORPORA.map((c) => ({ c, open: openCorpus(c) }));
  const present = opened.filter((o) => !o.open.absent);
  const out = [];

  out.push('## Corpora and pins', '');
  out.push('| corpus | pin (docs/eval/corpus-candidates.md) | HEAD found | at pin | tracked paths |', '| --- | --- | --- | --- | ---: |');
  for (const { c, open } of opened) {
    if (open.absent) {
      out.push(`| ${c.id} | \`${c.pin.slice(0, 10)}\` | absent | n/a | n/a |`);
      continue;
    }
    out.push(`| ${c.id} | \`${c.pin.slice(0, 10)}\` | \`${open.head.slice(0, 10)}\` | ${open.head === c.pin ? 'yes' : 'NO'} | ${String(tracked(open))} |`);
  }
  out.push('');

  const rows = [];
  const heads = present.map((o) => o.c.id);
  out.push('## Tracked-path drops per entry', '');
  out.push(`Each cell is \`dropped/source-extension\` for \`ls-files -z --cached --ignored --exclude <pattern>\`. The last column is the sum of source-extension paths over all measured corpora.`, '');
  out.push(`| pattern | ${heads.join(' | ')} | total src |`, `| --- | ${heads.map(() => '---:').join(' | ')} | ---: |`);
  const samples = [];
  for (const e of PROPOSED) {
    let totalSrc = 0;
    const cells = [];
    for (const { c, open } of present) {
      const d = drops(open, e.pattern);
      totalSrc += d.src;
      cells.push(`${String(d.total)}/${String(d.src)}`);
      if (d.total > 0) samples.push({ pattern: e.pattern, corpus: c.id, ...d });
    }
    rows.push({ e, totalSrc });
    out.push(`| \`${e.pattern}\` | ${cells.join(' | ')} | ${String(totalSrc)} |`);
  }
  out.push('');
  out.push('### Sample dropped paths (up to five per entry and corpus, source-extension paths first)', '');
  for (const s of samples) {
    out.push(`- \`${s.pattern}\` in ${s.corpus}: ${String(s.total)} dropped, ${String(s.src)} source-extension; e.g. ${s.samples.map((p) => `\`${p}\``).join(', ')}`);
  }
  out.push('');
  out.push('### Draft decisions (mechanical; bundle-output entries need the sample evidence)', '');
  out.push('| pattern | ecosystem | mechanical decision | total src |', '| --- | --- | --- | ---: |');
  for (const { e, totalSrc } of rows) {
    out.push(`| \`${e.pattern}\` | ${e.ecosystem} | ${mechanical(e, totalSrc)} | ${String(totalSrc)} |`);
  }
  out.push('');

  const argv = argvBytes();
  out.push(`Argv of the full defaults list as \`--exclude <pattern>\` pairs: ${String(argv)} bytes (limit in the plan: 8192).`, '');

  const after = snapshotCore();
  out.push('### gsd-core clone integrity', '');
  out.push(`- before: \`git status --porcelain\` ${String(before.statusLines)} line(s) (sha ${before.statusSha}), \`.git/index\` sha256 ${before.indexSha256}`);
  out.push(`- after:  \`git status --porcelain\` ${String(after.statusLines)} line(s) (sha ${after.statusSha}), \`.git/index\` sha256 ${after.indexSha256}`);
  out.push(`- identical: ${before.statusSha === after.statusSha && before.indexSha256 === after.indexSha256 ? 'yes' : 'NO'}`);
  return out.join('\n');
}

function mechanical(e, totalSrc) {
  if (!MEASURED_ECOSYSTEMS.has(e.ecosystem)) return 'UNTRACKED-ONLY (not measured)';
  if (e.ecosystem === 'bundle-output') return totalSrc === 0 ? 'TRACKED-OK' : 'TRACKED-OK if samples are generated files';
  if (totalSrc === 0) return 'TRACKED-OK';
  if (totalSrc <= NEGLIGIBLE_ALLOWANCE) return 'TRACKED-OK only with the logged allowance, else UNTRACKED-ONLY';
  return 'UNTRACKED-ONLY';
}

function argvBytes() {
  const argv = ['ls-files', '-z', '--others', '--exclude-standard', ...PROPOSED.flatMap((e) => ['--exclude', e.pattern])];
  return argv.reduce((n, a) => n + Buffer.byteLength(a) + 1, 0);
}

