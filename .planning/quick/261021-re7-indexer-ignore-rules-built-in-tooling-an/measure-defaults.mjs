const gitEnv = (extra = {}) => ({ ...process.env, GIT_OPTIONAL_LOCKS: '0', LC_ALL: 'C', ...extra });

function git(args, cwd, extraEnv = {}) {
  const r = spawnSync('git', args, { cwd, env: gitEnv(extraEnv), maxBuffer: 1 << 30, encoding: 'buffer' });
  if (r.error) throw r.error;
  return { status: r.status, stdout: r.stdout, stderr: r.stderr.toString('utf8') };
}

function gitAsync(args, cwd, extraEnv = {}) {
  return new Promise((resolve, reject) => {
    const started = process.hrtime.bigint();
    const child = spawn('git', args, { cwd, env: gitEnv(extraEnv), stdio: ['ignore', 'pipe', 'pipe'] });
    const chunks = [];
    child.stdout.on('data', (c) => chunks.push(c));
    child.stderr.on('data', () => {});
    child.on('error', reject);
    child.on('close', (code) => {
      resolve({ code, out: Buffer.concat(chunks), ms: Number(process.hrtime.bigint() - started) / 1e6 });
    });
  });
}

const split0 = (buf) => buf.toString('utf8').split('\0').filter((s) => s !== '');

// ---------------------------------------------------------------- read-only gsd-core clone

function snapshotCore() {
  const dir = coreDir();
  const status = git(['status', '--porcelain'], dir);
  const lines = status.stdout.toString('utf8').split('\n').filter((l) => l !== '');
  const indexFile = path.join(dir, '.git', 'index');
  const sum = createHash('sha256').update(fs.readFileSync(indexFile)).digest('hex');
  return { statusLines: lines.length, statusSha: createHash('sha256').update(lines.join('\n')).digest('hex').slice(0, 12), indexSha256: sum };
}

// ---------------------------------------------------------------- corpus access

/** A corpus is {env, cwd} that makes `git ls-files` list the pinned tracked paths without writing into the clone. */
function openCorpus(c) {
  if (c.pinned) {
    const dir = coreDir();
    if (!fs.existsSync(path.join(dir, '.git'))) return { absent: `no clone at ${dir}` };
    const idx = path.join(scratchDir(), 're7-core-pin.index');
    fs.rmSync(idx, { force: true });
    const r = git(['read-tree', c.pin], dir, { GIT_INDEX_FILE: idx });
    if (r.status !== 0) return { absent: `read-tree of the pin failed: ${r.stderr.trim()}` };
    return { cwd: dir, env: { GIT_INDEX_FILE: idx }, head: c.pin };
  }
  const dir = path.join(scratchDir(), 'corpora', c.dir);
  if (!fs.existsSync(path.join(dir, '.git'))) return { absent: `no clone at corpora/${c.dir}` };
  const head = git(['rev-parse', 'HEAD'], dir);
  if (head.status !== 0) return { absent: `not a usable repository: ${head.stderr.trim().split('\n')[0]}` };
  return { cwd: dir, env: {}, head: head.stdout.toString('utf8').trim() };
}

function tracked(open) {
  const r = git(['ls-files', '-z', '--cached'], open.cwd, open.env);
  return r.status === 0 ? split0(r.stdout).length : -1;
}

function drops(open, pattern) {
  const r = git(['ls-files', '-z', '--cached', '--ignored', '--exclude', pattern], open.cwd, open.env);
  if (r.status !== 0) throw new Error(`git ls-files failed for ${pattern}: ${r.stderr}`);
  const paths = split0(r.stdout);
  const src = paths.filter((p) => SOURCE_EXT.has(path.extname(p).toLowerCase()));
  return { total: paths.length, src: src.length, samples: (src.length > 0 ? src : paths).slice(0, 5) };
}

