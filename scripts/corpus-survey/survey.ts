/**
 * Corpus survey: measures a checked-out directory for the candidate-corpus note (docs/eval/corpus-candidates.md).
 *
 * Usage: node scripts/corpus-survey/survey.ts <name> <dir> [--seed S] [--max-files N] [--grep-sample N] > out.json
 *
 * Read-only. Nothing in <dir> is executed, installed or built: files are listed (git ls-files, or a directory walk
 * when there is no .git), read as text, parsed with the TypeScript parser (syntax only), and searched with ripgrep.
 * TypeScript module resolution is run against the tracked tsconfig files with the real file system but without any
 * node_modules (none is installed), which is what a "no install" analysis would see.
 */
import { execFile, execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { promisify } from 'node:util';

import ts from 'typescript';

import {
  agentConfigPaths,
  ambiguityStats,
  classifyLicense,
  classifySpecifier,
  extractExportedNames,
  extractSpecifiers,
  isBarrel,
  isTestPath,
  percentile,
  rankBySeed,
} from './lib.ts';
import type { AmbiguityStats } from './lib.ts';

const execFileAsync = promisify(execFile);

const TSJS_EXT = new Set(['.ts', '.tsx', '.mts', '.cts', '.js', '.jsx', '.mjs', '.cjs']);
const GENERATED_MARK = /@generated|do not edit|auto-?generated|generated by|code generated/i;

export interface SurveyOptions {
  name: string;
  seed: string | number;
  /** Cap on the deterministic file sample used for exported names (the brief: 3,000). */
  maxFiles: number;
  /** Cap on exported names considered (unused when maxFiles governs; kept for symmetry in tests). */
  maxNames: number;
  /** Number of exported names whose whole-word ripgrep matches are counted (the brief: 200). */
  grepSample: number;
  /** Cap on sampled files whose imports are resolved (resolution is the slow step). */
  maxResolveFiles?: number;
}

export interface Resolution {
  total: number;
  resolved: number;
}

export interface SurveyResult {
  name: string;
  dir: string;
  options: { seed: string | number; maxFiles: number; grepSample: number; minNameLength: number };
  tracked: { files: number; bytes: number; byExtension: Record<string, number> };
  license: { spdx: string; file: string | null; otherLicenseFiles: Record<string, number> };
  agentConfigs: string[];
  tsJs: { files: number; lines: number; testFiles: number; declarationFiles: number; generatedMarkedFiles: number };
  tsconfig: { count: number; withReferences: number; withPaths: number; withExtends: number; extendsUnresolved: number; paths: string[] };
  workspacePackages: number;
  sample: { eligibleFiles: number; files: number; names: AmbiguityStats; multiFileShare: number; barrelFiles: number };
  resolution: { relative: Resolution; workspace: Resolution; external: Resolution; filesResolved: number };
  grep: {
    names: number;
    linesMedian: number;
    linesP90: number;
    linesMax: number;
    filesMedian: number;
    filesP90: number;
    filesMax: number;
    shareOver20Files: number;
  };
}

const MIN_NAME_LENGTH = 3;

function listFiles(dir: string): string[] {
  if (fs.existsSync(path.join(dir, '.git'))) {
    const out = execFileSync('git', ['-C', dir, 'ls-files', '-z'], { maxBuffer: 1 << 30, env: { ...process.env, GIT_OPTIONAL_LOCKS: '0' } }).toString('utf8');
    return out.split('\0').filter((s) => s !== '');
  }
  const out: string[] = [];
  const walk = (rel: string): void => {
    for (const e of fs.readdirSync(path.join(dir, rel), { withFileTypes: true })) {
      const r = rel === '' ? e.name : `${rel}/${e.name}`;
      if (e.isDirectory()) walk(r);
      else if (e.isFile()) out.push(r);
    }
  };
  walk('');
  return out;
}

function readText(dir: string, rel: string): string | undefined {
  try {
    return fs.readFileSync(path.join(dir, rel), 'utf8');
  } catch {
    return undefined;
  }
}

function countLines(text: string): number {
  if (text.length === 0) return 0;
  let n = 1;
  for (let i = text.indexOf('\n'); i !== -1; i = text.indexOf('\n', i + 1)) n++;
  return text.endsWith('\n') ? n - 1 : n;
}

interface TsconfigInfo {
  options: ts.CompilerOptions;
  hasReferences: boolean;
  hasPaths: boolean;
  hasExtends: boolean;
  extendsUnresolved: boolean;
}

function parseTsconfig(abs: string): TsconfigInfo | undefined {
  const read = ts.readConfigFile(abs, ts.sys.readFile);
  if (read.error !== undefined || read.config === undefined) return undefined;
  const raw = read.config as { references?: unknown; extends?: unknown; compilerOptions?: { paths?: unknown } };
  const host: ts.ParseConfigHost = {
    useCaseSensitiveFileNames: true,
    readDirectory: () => [],
    fileExists: ts.sys.fileExists,
    readFile: ts.sys.readFile,
  };
  const parsed = ts.parseJsonConfigFileContent(read.config, host, path.dirname(abs), undefined, abs);
  return {
    options: parsed.options,
    hasReferences: Array.isArray(raw.references) && raw.references.length > 0,
    hasPaths: parsed.options.paths !== undefined || raw.compilerOptions?.paths !== undefined,
    hasExtends: raw.extends !== undefined,
    extendsUnresolved: parsed.errors.some((e) => e.code === 6053),
  };
}

async function grepCounts(dir: string, names: readonly string[]): Promise<{ lines: number[]; files: number[] }> {
  const lines: number[] = [];
  const files: number[] = [];
  let next = 0;
  const worker = async (): Promise<void> => {
    for (;;) {
      const i = next++;
      if (i >= names.length) return;
      let stdout = '';
      try {
        ({ stdout } = await execFileAsync('rg', ['-w', '-F', '-c', '--no-ignore', '--hidden', '-g', '!.git', '--', names[i] as string, dir], { maxBuffer: 1 << 28 }));
      } catch (err) {
        const e = err as { code?: number; stdout?: string };
        if (e.code !== 1) throw err;
        stdout = e.stdout ?? '';
      }
      let l = 0;
      let f = 0;
      for (const row of stdout.split('\n')) {
        if (row === '') continue;
        const c = Number(row.slice(row.lastIndexOf(':') + 1));
        if (Number.isFinite(c)) {
          l += c;
          f++;
        }
      }
      lines[i] = l;
      files[i] = f;
    }
  };
  await Promise.all([worker(), worker(), worker(), worker()]);
  return { lines, files };
}

export async function surveyDirectory(dir: string, opts: SurveyOptions): Promise<SurveyResult> {
  const all = listFiles(dir);
  const byExtension: Record<string, number> = {};
  let bytes = 0;
  for (const rel of all) {
    const ext = path.posix.extname(rel) || '(none)';
    byExtension[ext] = (byExtension[ext] ?? 0) + 1;
    try {
      bytes += fs.statSync(path.join(dir, rel)).size;
    } catch {
      /* dangling symlink */
    }
  }

  // licence
  const licenseRe = /(^|\/)(LICEN[CS]E|COPYING)[^/]*$/i;
  const licenseFiles = all.filter((p) => licenseRe.test(p) && p.split('/').length <= 4);
  const rootLicense = licenseFiles.find((p) => !p.includes('/'));
  const rootSpdx = rootLicense !== undefined ? classifyLicense((readText(dir, rootLicense) ?? '').slice(0, 8000)) : 'NONE';
  const otherLicenseFiles: Record<string, number> = {};
  for (const p of licenseFiles) {
    if (p === rootLicense) continue;
    const k = classifyLicense((readText(dir, p) ?? '').slice(0, 8000));
    otherLicenseFiles[k] = (otherLicenseFiles[k] ?? 0) + 1;
  }

  // tsconfig and workspace packages
  const tsconfigPaths = all.filter((p) => /(^|\/)(tsconfig[^/]*|jsconfig)\.json$/.test(p));
  const infos = new Map<string, TsconfigInfo | undefined>();
  let withReferences = 0;
  let withPaths = 0;
  let withExtends = 0;
  let extendsUnresolved = 0;
  for (const rel of tsconfigPaths) {
    const info = parseTsconfig(path.join(dir, rel));
    infos.set(rel, info);
    if (info === undefined) continue;
    if (info.hasReferences) withReferences++;
    if (info.hasPaths) withPaths++;
    if (info.hasExtends) withExtends++;
    if (info.extendsUnresolved) extendsUnresolved++;
  }
  const workspaceNames = new Set<string>();
  for (const rel of all) {
    if (!/(^|\/)package\.json$/.test(rel)) continue;
    try {
      const j = JSON.parse(readText(dir, rel) ?? '{}') as { name?: unknown };
      if (typeof j.name === 'string') workspaceNames.add(j.name);
    } catch {
      /* not JSON */
    }
  }

  // TS/JS inventory
  const tsjs = all.filter((p) => TSJS_EXT.has(path.posix.extname(p)));
  let lines = 0;
  let testFiles = 0;
  let declarationFiles = 0;
  let generatedMarkedFiles = 0;
  const eligible: string[] = [];
  for (const rel of tsjs) {
    const text = readText(dir, rel);
    if (text === undefined) continue;
    lines += countLines(text);
    const isDecl = rel.endsWith('.d.ts') || rel.endsWith('.d.mts') || rel.endsWith('.d.cts');
    if (isDecl) declarationFiles++;
    if (isTestPath(rel)) testFiles++;
    if (GENERATED_MARK.test(text.slice(0, 1000))) generatedMarkedFiles++;
    if (!isDecl && !isTestPath(rel)) eligible.push(rel);
  }

  // deterministic sample: sha256(seed NUL path) order, first maxFiles
  const sampleFiles = rankBySeed(eligible, opts.seed, opts.maxFiles);
  const namesByFile = new Map<string, string[]>();
  let barrelFiles = 0;
  const rel: Resolution = { total: 0, resolved: 0 };
  const wsr: Resolution = { total: 0, resolved: 0 };
  const ext: Resolution = { total: 0, resolved: 0 };
  let filesResolved = 0;
  const maxResolve = opts.maxResolveFiles ?? 1500;
  const tsconfigDirs = new Set(tsconfigPaths.filter((p) => path.posix.basename(p) === 'tsconfig.json').map((p) => path.posix.dirname(p)));
  const nearest = (file: string): string | undefined => {
    let d = path.posix.dirname(file);
    for (;;) {
      if (tsconfigDirs.has(d)) return d === '.' ? 'tsconfig.json' : `${d}/tsconfig.json`;
      if (d === '.' || d === '/') return undefined;
      d = path.posix.dirname(d);
    }
  };
  const fallback: ts.CompilerOptions = { moduleResolution: ts.ModuleResolutionKind.Bundler, module: ts.ModuleKind.ESNext };
  for (const file of sampleFiles) {
    const text = readText(dir, file);
    if (text === undefined) continue;
    namesByFile.set(file, extractExportedNames(text, file));
    if (isBarrel(text, file)) barrelFiles++;
  }
  // resolution uses the sample ordered by the same ranking, first maxResolve files
  for (const file of sampleFiles.slice(0, maxResolve)) {
    const text = readText(dir, file);
    if (text === undefined) continue;
    const cfg = nearest(file);
    const options = (cfg !== undefined ? infos.get(cfg)?.options : undefined) ?? fallback;
    filesResolved++;
    for (const spec of extractSpecifiers(text, file)) {
      const kind = classifySpecifier(spec, workspaceNames);
      const bucket = kind === 'relative' ? rel : kind === 'workspace' ? wsr : ext;
      bucket.total++;
      const r = ts.resolveModuleName(spec, path.join(dir, file), options, ts.sys);
      if (r.resolvedModule !== undefined) bucket.resolved++;
    }
  }

  const names = ambiguityStats(namesByFile);
  const pool = [...new Set([...namesByFile.values()].flat())].filter((n) => n.length >= MIN_NAME_LENGTH);
  const chosen = rankBySeed(pool, `${opts.seed}:grep`, opts.grepSample);
  const g = await grepCounts(dir, chosen);
  const over20 = g.files.filter((f) => f > 20).length;

  return {
    name: opts.name,
    dir,
    options: { seed: opts.seed, maxFiles: opts.maxFiles, grepSample: opts.grepSample, minNameLength: MIN_NAME_LENGTH },
    tracked: { files: all.length, bytes, byExtension },
    license: { spdx: rootSpdx, file: rootLicense ?? null, otherLicenseFiles },
    agentConfigs: agentConfigPaths(all),
    tsJs: { files: tsjs.length, lines, testFiles, declarationFiles, generatedMarkedFiles },
    tsconfig: { count: tsconfigPaths.length, withReferences, withPaths, withExtends, extendsUnresolved, paths: tsconfigPaths.slice(0, 40) },
    workspacePackages: workspaceNames.size,
    sample: {
      eligibleFiles: eligible.length,
      files: namesByFile.size,
      names,
      multiFileShare: names.distinctNames === 0 ? 0 : names.multiFileNames / names.distinctNames,
      barrelFiles,
    },
    resolution: { relative: rel, workspace: wsr, external: ext, filesResolved },
    grep: {
      names: chosen.length,
      linesMedian: percentile(g.lines, 50),
      linesP90: percentile(g.lines, 90),
      linesMax: Math.max(0, ...g.lines),
      filesMedian: percentile(g.files, 50),
      filesP90: percentile(g.files, 90),
      filesMax: Math.max(0, ...g.files),
      shareOver20Files: chosen.length === 0 ? 0 : over20 / chosen.length,
    },
  };
}

function flag(args: string[], name: string, dflt: string): string {
  const i = args.indexOf(name);
  return i !== -1 && args[i + 1] !== undefined ? (args[i + 1] as string) : dflt;
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  const [name, dir] = args;
  if (name === undefined || dir === undefined) {
    process.stderr.write('usage: node scripts/corpus-survey/survey.ts <name> <dir> [--seed S] [--max-files N] [--grep-sample N]\n');
    process.exit(2);
  }
  const result = await surveyDirectory(path.resolve(dir), {
    name,
    seed: flag(args, '--seed', '20261017'),
    maxFiles: Number(flag(args, '--max-files', '3000')),
    maxNames: 0,
    grepSample: Number(flag(args, '--grep-sample', '200')),
  });
  process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
}
